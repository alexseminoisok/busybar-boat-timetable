#!/usr/bin/env python3
"""Generate the Pier setting for Boat Timetable from one list.

Writes community.boat_timetable/appmeta/settings.json (the Setup → Pier
picker on the bar) and rewrites the PIERS table in scripts/main.js between
its BEGIN/END markers, so the two can't drift apart.

IDs are TfL river-bus "NaptanFerryPort" stop points (930G…); one ID covers
all berths of a pier. Listed west to east along the Thames.
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.join(HERE, "community.boat_timetable")
DEFAULT = "930GMIL"

PIERS = [   # (TfL id, label on the bar; the app adds " Pier" for the stop name)
    ("930GPUT", "Putney"),
    ("930GWRQ", "Wandsworth Riverside"),
    ("930GPLW", "St Mary's Wandsworth"),
    ("930GCHP", "Chelsea Harbour"),
    ("930GBSE", "Cadogan"),
    ("930GBSP", "Battersea Power Station"),
    ("930GSGW", "Vauxhall"),
    ("930GMBK", "Millbank"),
    ("930GWMR", "Westminster"),
    ("930GWMP", "London Eye Waterloo"),
    ("930GEMB", "Embankment"),
    ("930GBFR", "Blackfriars"),
    ("930GSWK", "Bankside"),
    ("930GLBR", "London Bridge City"),
    ("930GTMP", "Tower"),
    ("930GCAW", "Canary Wharf"),
    ("930GNEL", "Rotherhithe"),
    ("930GGLP", "Greenland Surrey Quays"),
    ("930GMHT", "Masthouse Terrace"),
    ("930GGNW", "Greenwich"),
    ("930GMIL", "North Greenwich"),
    ("930GWRF", "Royal Wharf"),
    ("930GWAS", "Woolwich Arsenal"),
    ("930GBRVS", "Barking Riverside"),
]


def write_settings():
    assert len(PIERS) <= 32, "the bar's enum picker allows at most 32 options"
    assert DEFAULT in dict(PIERS)
    schema = {
        "format_version": 1,
        "version": 1,
        "fields": {
            "pier": {
                "label": "Pier",
                "description": "Uber Boat pier to show departures for.",
                "type": "enum",
                "default": DEFAULT,
                "options": [{"value": pid, "label": label} for pid, label in PIERS],
            }
        },
    }
    path = os.path.join(APP, "appmeta", "settings.json")
    with open(path, "w") as f:
        json.dump(schema, f, indent=2)
        f.write("\n")
    print(f"Wrote {os.path.relpath(path, HERE)} ({len(PIERS)} piers, default {DEFAULT})")


def write_js_table():
    path = os.path.join(APP, "scripts", "main.js")
    src = open(path).read()
    rows = ",\n".join(f'  "{pid}": "{label} Pier"' for pid, label in PIERS)
    table = ("// BEGIN PIERS (generated by build_settings.py — edit the list there)\n"
             f"var PIERS = {{\n{rows}\n}};\n"
             "// END PIERS")
    new, n = re.subn(r"// BEGIN PIERS.*?// END PIERS", lambda m: table, src, flags=re.S)
    if n != 1:
        raise SystemExit("main.js: BEGIN/END PIERS markers not found")
    with open(path, "w") as f:
        f.write(new)
    print(f"Updated PIERS table in {os.path.relpath(path, HERE)}")


if __name__ == "__main__":
    write_settings()
    write_js_table()
