#!/usr/bin/env python3
"""Generate Boat Timetable's Setup fields (Pier, Text colour, Background).

Writes src/appmeta/settings.json (the Setup pickers on
the bar) and rewrites the PIERS table in scripts/main.js between its
BEGIN/END markers, so the two can't drift apart. Colour values must match
the theme names in main.js's THEMES, background values the keys of its
BACKGROUNDS.

IDs are TfL river-bus "NaptanFerryPort" stop points (930G…); one ID covers
all berths of a pier. Listed west to east along the Thames.
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.join(HERE, "src")
DEFAULT = "930GMIL"

PIERS = [   # (TfL id, label on the bar; the app adds " Pier" for the stop name)
    ("930GPUT", "Putney"),
    ("930GWRQ", "Wandsworth Riverside"),
    ("930GPLW", "St Mary's Wandsworth"),
    ("930GCHP", "Chelsea Harbour"),
    ("930GBSE", "Cadogan"),
    ("930GBSP", "Battersea Power Station"),
    ("930GSGW", "Vauxhall"),
    ("930GMBK", "Millbank"),
    ("930GWMR", "Westminster"),
    ("930GWMP", "London Eye Waterloo"),
    ("930GEMB", "Embankment"),
    ("930GBFR", "Blackfriars"),
    ("930GSWK", "Bankside"),
    ("930GLBR", "London Bridge City"),
    ("930GTMP", "Tower"),
    ("930GCAW", "Canary Wharf"),
    ("930GNEL", "Rotherhithe"),
    ("930GGLP", "Greenland Surrey Quays"),
    ("930GMHT", "Masthouse Terrace"),
    ("930GGNW", "Greenwich"),
    ("930GMIL", "North Greenwich"),
    ("930GWRF", "Royal Wharf"),
    ("930GWAS", "Woolwich Arsenal"),
    ("930GBRVS", "Barking Riverside"),
]

COLOURS = [  # (theme name in main.js THEMES, label on the bar)
    ("cyan", "Cyan"),
    ("white", "White"),      # moonlight
    ("lilac", "Lilac"),      # matches the indigo glow
    ("green", "Green"),
    ("yellow", "Yellow"),    # lamplight on the water
    ("amber", "Amber"),
    ("pink", "Pink"),
    ("red", "Red"),
]
DEFAULT_COLOUR = "cyan"

BACKGROUNDS = [  # (key in main.js BACKGROUNDS, label on the bar)
    ("animated", "Animated"),
    ("gray", "Gray"),
    ("black", "Black"),
]
DEFAULT_BACKGROUND = "animated"


def write_settings():
    assert len(PIERS) <= 32, "the bar's enum picker allows at most 32 options"
    assert DEFAULT in dict(PIERS)
    assert DEFAULT_COLOUR in dict(COLOURS)
    assert DEFAULT_BACKGROUND in dict(BACKGROUNDS)
    schema = {
        "format_version": 1,
        "version": 1,
        "fields": {
            "pier": {
                "label": "Pier",
                "description": "Uber Boat pier to show departures for.",
                "type": "enum",
                "default": DEFAULT,
                "options": [{"value": pid, "label": label} for pid, label in PIERS],
            },
            "colour": {
                "label": "Text colour",
                "description": "Colour of the departures text.",
                "type": "enum",
                "default": DEFAULT_COLOUR,
                "options": [{"value": v, "label": label} for v, label in COLOURS],
            },
            "background": {
                "label": "Background",
                "description": "Animated river at night, or plain dark gray or black.",
                "type": "enum",
                "default": DEFAULT_BACKGROUND,
                "options": [{"value": v, "label": label} for v, label in BACKGROUNDS],
            },
        },
    }
    path = os.path.join(APP, "appmeta", "settings.json")
    with open(path, "w") as f:
        json.dump(schema, f, indent=2)
        f.write("\n")
    print(f"Wrote {os.path.relpath(path, HERE)} ({len(PIERS)} piers, default {DEFAULT}; "
          f"{len(COLOURS)} colours, default {DEFAULT_COLOUR}; "
          f"{len(BACKGROUNDS)} backgrounds, default {DEFAULT_BACKGROUND})")


def write_js_table():
    path = os.path.join(APP, "main.js")
    src = open(path).read()
    rows = ",\n".join(f'  "{pid}": "{label} Pier"' for pid, label in PIERS)
    table = ("// BEGIN PIERS (generated by build_settings.py — edit the list there)\n"
             f"var PIERS = {{\n{rows}\n}};\n"
             "// END PIERS")
    new, n = re.subn(r"// BEGIN PIERS.*?// END PIERS", lambda m: table, src, flags=re.S)
    if n != 1:
        raise SystemExit("main.js: BEGIN/END PIERS markers not found")
    with open(path, "w") as f:
        f.write(new)
    print(f"Updated PIERS table in {os.path.relpath(path, HERE)}")


if __name__ == "__main__":
    write_settings()
    write_js_table()
